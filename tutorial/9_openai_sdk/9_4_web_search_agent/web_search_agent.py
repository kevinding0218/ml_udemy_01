from openai import OpenAI
from getpass import getpass

api_key = getpass("OpenAI API Key: ")

client = OpenAI(api_key=api_key)

response = client.responses.create(
    model="gpt-4.1-mini",
    tools=[
        {
            "type": "web_search_preview"
        }
    ],
    input="What are today's top AI news stories?"
)

print(response.output_text)

question = """
Summarize the latest developments in Artificial Intelligence
and provide the answer in five bullet points.
"""

response = client.responses.create(
    model="gpt-4.1-mini",
    tools=[{"type": "web_search_preview"}],
    input=question
)

print(response.output_text)

def research_agent(question):

    response = client.responses.create(
        model="gpt-4.1-mini",

        tools=[
            {
                "type": "web_search_preview"
            }
        ],

        instructions="""
        You are an AI research assistant.
        Search the web when needed.
        Summarize findings clearly.
        Use bullet points.
        """,

        input=question
    )

    return response.output_text



print(
    research_agent(
        "What are the latest announcements from OpenAI this week?"
    )
)

print(
    research_agent(
        "Summarize the latest news about NVIDIA and AI."
    )
)

